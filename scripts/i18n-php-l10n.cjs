const TARGETS = [
	'lib/Controller/TaskController.php',
	'lib/Controller/WorkspaceController.php',
	'lib/Controller/SettingsController.php',
	'lib/Service/AnalysisService.php',
	'lib/Service/AiClient.php',
	'lib/Service/DeckBridge.php',
	'lib/Command/AnalyzeCommand.php',
	'lib/Command/ScanCommand.php',
]

const used = new Map()
for (const rel of TARGETS) {
	const full = path.join(ROOT, rel)
	let text = fs.readFileSync(full, 'utf8')
	const original = text

	// 1) import IL10N once
	if (!text.includes('use OCP\\IL10N;')) {
		const ocp = text.match(/^use OCP\\[^\n]*\n/m)
		const anyUse = [...text.matchAll(/^use [^\n]*\n/gm)].pop()
		if (ocp) {
			text = text.replace(ocp[0], ocp[0] + 'use OCP\\IL10N;\n')
		} else if (anyUse) {
			text = text.replace(anyUse[0], anyUse[0] + 'use OCP\\IL10N;\n')
		} else {
			throw new Error(`no use statement in ${rel}`)
		}
	}

	// 2) replace whitelisted literals, longest first so prefixes do not win
	const keys = Object.keys(MAP).sort((a, b) => b.length - a.length)
	for (const zh of keys) {
		const needle = `'${zh}'`
		if (!text.includes(needle)) continue
		const en = MAP[zh].replace(/'/g, "\\'")
		text = text.split(needle).join(`$this->l10n->t('${en}')`)
		used.set(MAP[zh], zh)
	}

	// 3) inject the dependency right before the closing paren of the constructor
	if (!text.includes('private IL10N $l10n')) {
		const ctor = text.match(/__construct\(([\s\S]*?)\n\t\) \{/)
		if (!ctor) throw new Error(`no constructor in ${rel}`)
		const body = ctor[1].replace(/,\s*$/, '')
		text = text.replace(ctor[0], `__construct(${body},\n\t\tprivate IL10N $l10n,\n\t) {`)
	}

	if (text !== original) fs.writeFileSync(full, text)
	console.log(`${rel}: ${text === original ? 'unchanged' : 'updated'}`)
}

// 4) merge into the zh_CN catalogue produced by the frontend pass
const l10nPath = path.join(ROOT, 'l10n', 'zh_CN.json')
const existing = JSON.parse(fs.readFileSync(l10nPath, 'utf8'))
for (const [en, zh] of used) existing.translations[en] = zh
const sorted = Object.fromEntries(Object.entries(existing.translations).sort(([a], [b]) => a.localeCompare(b)))
fs.writeFileSync(l10nPath, JSON.stringify({ translations: sorted, pluralForm: existing.pluralForm }, null, 2) + '\n')
fs.writeFileSync(
	path.join(ROOT, 'l10n', 'zh_CN.js'),
	`OC.L10N.register(\n\t"todofolder",\n\t${JSON.stringify(sorted, null, 2).replace(/\n/g, '\n\t')},\n\t"nplurals=1; plural=0;"\n);\n`,
)
console.log(`catalogue entries: ${Object.keys(sorted).length} (+${used.size} from PHP)`)
